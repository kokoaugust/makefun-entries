/** One generated user of the scenario. */
export interface ScenarioUser {
  readonly id: number;
  readonly login: string;
  readonly name: string;
  readonly email: string;
}

/** `count` users with unique logins, deterministic for `rng` (the suite's own generator, ported). */
export function generateUsers(rng: Rng, count: number): ScenarioUser[] {
  const used = new Set<string>();
  const users: ScenarioUser[] = [];
  for (let i = 0; i < count; i += 1) {
    const first = rng.pick(FIRST_NAMES);
    const last = rng.pick(LAST_NAMES);
    const base = `${first}${last}`.replace(/[^a-z0-9-]/g, '');
    let login = base;
    let suffix = 2;
    while (used.has(login)) {
      login = `${base}-${suffix}`;
      suffix += 1;
    }
    used.add(login);
    users.push({ id: 1000 + i, login, name: `${first} ${last}`, email: `${login}@example.invalid` });
  }
  return users;
}

/** The scenario's users; the first of them is the viewer — the login the trial's token owns. */
export const SCENARIO_USERS: readonly ScenarioUser[] = generateUsers(scenarioRng('users'), 12);

/** The token owner's identity on this forge: repositories, commits and answers live under it. */
export const VIEWER: ScenarioUser = SCENARIO_USERS[0] as ScenarioUser;

